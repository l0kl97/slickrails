#!/bin/sh
# Prints the hashes of every template of every released kit version, from the release tags (never by hand):
#   sh scripts/release-hashes.sh > templates/release-hashes
# One line per template version: <git blob hash> <template path> <first release that shipped it>.
# The installer uses it for repos without a manifest (installed before 1.6.0): a file that is byte for byte the template
# of a release was never edited and is replaced. Run it after tagging a release; the test suite checks it is current.
set -eu

KIT_DIR="$(cd "$(dirname "$0")/.." && pwd)"
TAGS="$(git -C "$KIT_DIR" tag -l 'v*' --sort=v:refname)"
if [ -z "$TAGS" ]; then
  echo "release-hashes: no release tags here (git fetch --tags)" >&2
  exit 1
fi

echo "# slickrails release templates: blob hash, template, first release. Generated by scripts/release-hashes.sh; do not edit."
for TAG in $TAGS; do
  # ls-tree prints "<mode> blob <hash>\t<path>"; the blob hash is what `git hash-object` gives for the same content
  git -C "$KIT_DIR" ls-tree -r "$TAG" | awk -v v="${TAG#v}" '
    $2 == "blob" && ($4 ~ /^templates\// || $4 ~ /^SLICKRAILS(\.[a-z][a-z])?\.md$/) && $4 != "templates/release-hashes" { print $3, $4, v }'
done | awk '!seen[$1 " " $2]++'
