// Builds self-contained scene pages: src/lib + src/scenes/<name>.js + assets/logo.svg shapes
// → scenes/<name>.html (no network, no external files). `node build.mjs`
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.dirname(fileURLToPath(import.meta.url));
const read = (p) => fs.readFileSync(path.join(ROOT, p), 'utf8');

import { SCENE_NAMES } from './scene-names.mjs';

// The logo is never redrawn: take the shapes from assets/logo.svg as they are.
const logoSvg = read('../logo.svg');
const shapes = logoSvg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').replace(/<!--[\s\S]*?-->/g, '').trim();
if (!shapes.includes('#A8FF06')) throw new Error('assets/logo.svg changed shape — check build.mjs');

const lib = read('src/lib/motion.js');
const missing = SCENE_NAMES.filter((n) => !fs.existsSync(path.join(ROOT, `src/scenes/${n}.js`)));
if (missing.length) console.warn('skipping missing scenes:', missing.join(', '));
const sceneJs = Object.fromEntries(SCENE_NAMES.filter((n) => !missing.includes(n)).map((n) => [n, read(`src/scenes/${n}.js`)]));

function page({ title, w, h, body }) {
  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=${w}">
<title>${title}</title>
<!-- GENERATED by build.mjs from src/ — edit the sources, not this file. -->
<style>
  html, body { margin: 0; background: #0B0F0E; overflow: hidden; }
  svg { display: block; }
  text { font-kerning: normal; font-variant-ligatures: none; }
</style>
</head>
<body>
<svg id="stage" xmlns="http://www.w3.org/2000/svg" width="${w}" height="${h}" viewBox="0 0 ${w} ${h}"></svg>
<script>
const LOGO_SHAPES = ${JSON.stringify(shapes)};
${lib}
${body}
</script>
</body>
</html>
`;
}

// Boot: two instances. A plays; B is frozen at t=0 and fades in over the last `xf`
// seconds, so the frame at t=dur is pixel-identical to t=0 (seamless loop).
const boot = (name) => `
(() => {
  const S = SCENES[${JSON.stringify(name)}];
  const stage = document.getElementById('stage');
  const ga = el('g', {}, stage), gb = el('g', {}, stage);
  const A = S.build(ga), B = S.build(gb);
  B.seek(0);
  window.SCENE = { name: ${JSON.stringify(name)}, w: S.w, h: S.h, dur: S.dur, loop: S.loop, poster: S.poster, alt: S.alt };
  window.seek = (t) => {
    A.seek(t);
    const x = S.loop ? prog(t, S.dur - S.xf, S.dur) : 0;
    if (S.xfMode === 'dip') {
      // end and start differ in hue (red vs green): go through the background instead of blending
      set(ga, { opacity: 1 - clamp(x * 2) }); show(gb, x > 0.5); set(gb, { opacity: clamp(x * 2 - 1) });
    } else { show(gb, x > 0); set(gb, { opacity: x }); }
  };
  const q = new URLSearchParams(location.search);
  if (q.has('render')) { window.seek(+q.get('t') || 0); return; }
  // Preview only (never used for rendering): play in real time, ?t= pauses at a time.
  if (q.has('t')) { window.seek(+q.get('t')); return; }
  const t0 = performance.now();
  const loop = () => { window.seek(((performance.now() - t0) / 1000) % S.dur); requestAnimationFrame(loop); };
  loop();
})();`;

fs.mkdirSync(path.join(ROOT, 'scenes'), { recursive: true });
for (const n of Object.keys(sceneJs)) {
  fs.writeFileSync(path.join(ROOT, 'scenes', `${n}.html`), page({ title: `slickrails · ${n}`, w: 1000, h: 560, body: `${sceneJs[n]}\n${boot(n)}` }));
}

// Showreel: every scene module + the reel composition + the soundtrack synth.
if (!missing.length && fs.existsSync(path.join(ROOT, 'src/reel/showreel.js'))) {
  const body = [...SCENE_NAMES.map((n) => sceneJs[n]), read('src/reel/audio.js'), read('src/reel/showreel.js')].join('\n');
  fs.writeFileSync(path.join(ROOT, 'scenes', 'showreel.html'), page({ title: 'slickrails · showreel', w: 1920, h: 1080, body }));
}
console.log('built', fs.readdirSync(path.join(ROOT, 'scenes')).join(', '));
